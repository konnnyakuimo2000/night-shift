        public static NewsArticle FeaturedFor(int day) => Featured.TryGetValue(day, out var a) ? a : null;

        public static List<NewsArticle> Fillers3(int day)
        {
            var list = new List<NewsArticle>();
            for (int i = 0; i < 3; i++)
            {
                var f = Fillers[(day * 3 + i) % Fillers.Length];
                list.Add(new NewsArticle { Category = f[0], Headline = f[1], Body = "", New = i == 0 });
            }
            return list;
        }

        /// <summary>前夜の結果の記事（自分の会社）</summary>
        public static List<NewsArticle> Company(Core.CareerRecord career, int day)
        {
            var list = new List<NewsArticle>();
            var prev = career.Night(day - 1);
            const string C = "ネクサスコーポレーション";
            if (prev != null && prev.damaged)
                list.Add(new NewsArticle { Category = "経済", Headline = $"{C}でシステム障害 原因を調査中", Body = $"{C}の社内システムで、昨夜障害が発生した。同社は「顧客への影響を調査している」としている。" });
            if (career.HasFlag("NEWS_DEFACED"))
                list.Add(new NewsArticle { Category = "コンピュータ", Headline = $"{C}のホームページ、意味不明の文字に", Body = "同社のホームページが一時、読めない文字の羅列に書き換えられていた。" });
            if (career.HasFlag("NEWS_BLACKOUT"))
                list.Add(new NewsArticle { Category = "国内", Headline = "都内のオフィスビルで深夜に停電", Body = "停電は約10分間続いた。原因は調査中。" });
            if (career.trust <= 30)
                list.Add(new NewsArticle { Category = "経済", Headline = $"{C}、大口取引先が契約見直し 株価急落", Body = "相次ぐシステム障害を受け、取引先の間で同社との契約を見直す動きが広がっている。" });
            if (career.ConsecutiveRank("D", day - 1) >= 2)
                list.Add(new NewsArticle { Category = "経済", Headline = $"{C}、夜間のシステム管理を外部委託へ検討", Body = "関係者によると、同社は夜間のシステム管理を外部の会社に任せることを検討している。" });
            return list;
        }

